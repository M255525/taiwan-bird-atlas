/* ---------- 工具 ---------- */
BA.parseMonths = function(s){
  var set = {};
  String(s).split(',').forEach(function(part){
    var p = part.split('-').map(Number), a = p[0], b = p.length > 1 ? p[1] : p[0];
    for (var m = a, n = 0; n < 12; m = m % 12 + 1, n++){ set[m] = 1; if (m === b) break; }
  });
  return set;
};
BA.BIRDS.forEach(function(b){
  b.shape = Object.assign({}, BA.SHAPES[b.body], b.sh || {});
  b.at.forEach(function(a){ a.months = BA.parseMonths(a.m); a.regions = a.r.split(' '); a.spots = a.s ? a.s.split(' ') : null; });
});
BA.birdById = {}; BA.BIRDS.forEach(function(b){ BA.birdById[b.id] = b; });
BA.spotById = {}; BA.SPOTS.forEach(function(p){ BA.spotById[p.id] = p; });
BA.regionById = {}; BA.REGIONS.forEach(function(r){ BA.regionById[r.id] = r; });

/* 唯一查詢入口：某區域（可限定熱點）、棲地、月份看得到的鳥 */
BA.birdsFor = function(region, hab, month, spotId){
  var sp = spotId ? BA.spotById[spotId] : null;
  return BA.BIRDS.filter(function(b){
    if (sp && ((b.minE && sp.elev < b.minE) || (b.maxE && sp.elev > b.maxE))) return false;
    return b.at.some(function(a){
      return a.h === hab && a.months[month] && a.regions.indexOf(region) >= 0 && (!sp || !a.spots || a.spots.indexOf(sp.id) >= 0);
    });
  });
};
/* 某鳥在某棲地一年中出現的月份（可限定區域） */
BA.monthsOf = function(b, hab, region){
  var out = {};
  b.at.forEach(function(a){
    if (a.h !== hab || (region && a.regions.indexOf(region) < 0)) return;
    for (var m in a.months) out[m] = 1;
  });
  return out;
};
/* 某鳥一年中至少有一個月看得到的熱點 */
BA.spotsOf = function(b){
  return BA.SPOTS.filter(function(p){
    return p.h.some(function(h){ for (var m = 1; m <= 12; m++) if (BA.birdsFor(p.r, h, m, p.id).indexOf(b) >= 0) return true; return false; });
  });
};
